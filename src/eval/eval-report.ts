import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Renders data/eval/results.json into the artifacts the README slice embeds:
// a markdown table fragment (data/eval/report.md) and a bar chart
// (data/eval/eval-results.svg). Hand-rolled SVG keeps chart libs out of the deps.
export function evalReport() {
  const r = JSON.parse(readFileSync(join(process.cwd(), "data/eval/results.json"), "utf8")) as {
    timestamp?: string;
    sha?: string;
    model?: string;
    judge?: string;
    retrieval?: Record<string, number>;
    generation?: Record<string, number>;
  };

  const pct = (v: number) => `${Math.round(v * 100)}%`;

  const rows: { name: string; value: number; note: string }[] = [];
  const retrievalNotes: Record<string, string> = {
    hit_at_5: "erwarteter Artikel/Erwägungsgrund in Top 5",
    mrr_at_5: "mittlere Position des ersten Treffers",
    context_recall: "Anteil aller erwarteten Abschnitte gefunden",
  };
  const generationNotes: Record<string, string> = {
    faithfulness: "Anteil belegter Aussagen (LLM-Judge)",
    relevancy: "Antwort beantwortet die Frage (LLM-Judge)",
    refusal_rate: "Abstention-Fragen korrekt abgelehnt",
  };
  for (const [k, v] of Object.entries(r.retrieval ?? {})) {
    rows.push({ name: k, value: v, note: retrievalNotes[k] ?? "" });
  }
  for (const [k, v] of Object.entries(r.generation ?? {})) {
    rows.push({ name: k, value: v, note: generationNotes[k] ?? "" });
  }

  if (rows.length === 0) {
    console.error(
      "no metrics in data/eval/results.json; run evaluate-retrieval/evaluate-generation first",
    );
    process.exit(1);
  }

  // markdown fragment for the README slice (manually edit and embed it)
  const meta = [
    r.model ? `Modell: \`${r.model}\`` : null,
    r.judge ? `Judge: \`${r.judge}\`` : null,
    r.sha ? `Commit: \`${r.sha}\`` : null,
  ]
    .filter(Boolean)
    .join(" · ");
  const md = [
    `<!-- generated by eval-report, ${r.timestamp ?? "unknown time"} — review and paste into README -->`,
    `| Metrik | Wert | Bedeutung |`,
    `|---|---|---|`,
    ...rows.map((row) => `| ${row.name} | ${pct(row.value)} | ${row.note} |`),
    "",
    `_${meta}_`,
    "",
  ].join("\n");
  writeFileSync(join(process.cwd(), "data/eval/report.md"), md);

  // horizontal bar chart, 0-100%
  const W = 560;
  const rowH = 40;
  const barX = 170;
  const H = rows.length * rowH + 20;
  const barW = (v: number) => Math.max(2, (W - barX - 70) * v);
  const color = (name: string) =>
    name.startsWith("hit") || name.startsWith("mrr") || name.startsWith("context")
      ? "#0f766e" // retrieval: teal
      : "#b45309"; // generation: amber
  const svg = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="RAGnarok eval metrics">`,
    `  <style>text{font-family:system-ui,sans-serif;font-size:13px;fill:#1c1917}.note{fill:#78716c;font-size:11px}.val{font-weight:600}</style>`,
    `  <rect width="${W}" height="${H}" fill="#fafaf9"/>`,
    ...rows.map((row, i) => {
      const y = i * rowH + 22;
      return [
        `  <text x="8" y="${y + 4}">${row.name}</text>`,
        `  <rect x="${barX}" y="${y - 10}" width="${barW(row.value)}" height="18" rx="3" fill="${color(row.name)}"/>`,
        `  <text class="val" x="${barX + barW(row.value) + 8}" y="${y + 4}">${pct(row.value)}</text>`,
        `  <text class="note" x="${barX}" y="${y + 18}">${row.note}</text>`,
      ].join("\n");
    }),
    `</svg>`,
    "",
  ].join("\n");
  writeFileSync(join(process.cwd(), "data/eval/eval-results.svg"), svg);

  console.log("wrote data/eval/report.md and data/eval/eval-results.svg");
}
